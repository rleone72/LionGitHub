-- Tabellen pro Schema und Tablespace
db2 "SELECT TABSCHEMA, TBSPACE, COUNT(*) AS TABELLEN
  FROM SYSCAT.TABLES
 WHERE TABSCHEMA LIKE 'SVCFNDB2%' AND TYPE = 'T'
 GROUP BY TABSCHEMA, TBSPACE
 ORDER BY TABSCHEMA, TBSPACE;"


-- Tabellen, die nicht in den TS_*-Tablespaces liegen (sollte leer sein) 
db2 "SELECT TABSCHEMA, TABNAME, TBSPACE \
  FROM SYSCAT.TABLES \
 WHERE TABSCHEMA LIKE 'SVCFNDB2%' AND TYPE = 'T' \
 AND TBSPACE NOT LIKE 'TS!_%' ESCAPE '!'"